#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# dependencies = ["pillow>=10.1"]
# ///
"""Rasterize a font into a 1-bpp Rust bitmap font module for the TFT.

  mkfont.py <font> <px-size> <chars> <out.rs>

<font> is a TTF/OTF (rendered at <px-size>, thresholded) or an X11 bitmap
font (.pcf / .pcf.gz — copied pixel-exact, <px-size> is ignored). <chars>
is the subset to include, or `ascii` for all of printable ASCII 0x20..0x7E
stored contiguously (glyph = (ch - 0x20) * bytes-per-glyph; no lookup
table). Each glyph is cropped to one common cell (union of ink rows over
the subset, so baselines align), and the module defines:

  pub const CELL_H: u16, ADV: u16  cell rows / cell width (monospace only)
  pub const GLYPHS: &[(u8, u16)]   (char, offset into DATA), sorted; empty
                                   in `ascii` mode
  pub const DATA: &[u8]            CELL_H rows x ceil(ADV/8) bytes, MSB first
  pub static FONT: crate::tft::Font  the above bundled for the glyph engine

The firmware blits each cell with set-window + fg/bg expansion, so a full
cell (including the blank space glyph) always overwrites what was there.

The firmware's fonts:
  main screens: font/inb.otf (Inconsolata LGC Bold, SIL OFL — font/OFL.txt)
    mkfont.py font/inb.otf 30 '0123456789 .-VAWhm:TCD+vb' ../rust/src/font.rs
  small text (PD screen): font/7x13B.pcf.gz (X11 misc-fixed 7x13 bold,
  public domain)
    mkfont.py font/7x13B.pcf.gz 0 ascii ../rust/src/font_small.rs
"""
import gzip
import sys

from PIL import Image, ImageDraw, ImageFont, PcfFontFile


def load(path, size):
    if path.endswith((".pcf", ".pcf.gz")):
        opener = gzip.open if path.endswith(".gz") else open
        with opener(path, "rb") as f:
            return PcfFontFile.PcfFontFile(f).to_imagefont()
    return ImageFont.truetype(path, size)


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    path, size, chars, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    font = load(path, size)
    contiguous = chars == "ascii"
    if contiguous:
        chars = "".join(chr(c) for c in range(0x20, 0x7F))

    advs = {font.getlength(c) for c in chars}
    if len(advs) != 1:
        sys.exit("not monospace over this subset: advances %s" % sorted(advs))
    adv = round(advs.pop())

    # common cell: union of ink rows over the subset (keeps baselines aligned)
    boxes = [font.getbbox(c) for c in chars if c != " "]
    top = min(b[1] for b in boxes)
    bot = max(b[3] for b in boxes)
    cell_h = bot - top
    bpr = (adv + 7) // 8

    data = bytearray()
    glyphs = []
    for c in (chars if contiguous else sorted(chars)):
        img = Image.new("L", (adv, bot + 1), 0)
        ImageDraw.Draw(img).text((0, 0), c, font=font, fill=255)
        glyphs.append((c, len(data)))
        for y in range(top, bot):
            row = 0
            for x in range(adv):
                if img.getpixel((x, y)) > 127:
                    row |= 1 << (bpr * 8 - 1 - x)
            data += row.to_bytes(bpr, "big")

    with open(out, "w") as f:
        f.write("//! GENERATED by tools/mkfont.py — do not edit.\n")
        f.write("//!   mkfont.py %s %d '%s'\n" % (path.rsplit("/", 1)[-1], size,
                                                  "ascii" if contiguous else chars))
        f.write("//! %d glyphs, cell %dx%d, %d bytes.\n\n" % (len(glyphs), adv, cell_h, len(data)))
        f.write("use crate::tft::Font;\n\n")
        f.write("pub const CELL_H: u16 = %d;\n" % cell_h)
        f.write("pub const ADV: u16 = %d;\n\n" % adv)
        f.write("pub static FONT: Font = Font {\n    adv: ADV,\n    cell_h: CELL_H,\n")
        f.write("    first: 0x%02X,\n    glyphs: GLYPHS,\n    data: DATA,\n};\n\n" %
                (0x20 if contiguous else 0))
        f.write("pub const GLYPHS: &[(u8, u16)] = &[\n")
        if not contiguous:
            for c, off in glyphs:
                f.write("    (b'%s', %d),\n" % (c.replace("'", "\\'"), off))
        f.write("];\n\npub const DATA: &[u8] = &[\n")
        for i in range(0, len(data), 16):
            f.write("    %s\n" % " ".join("0x%02X," % b for b in data[i : i + 16]))
        f.write("];\n")
    print("%s: %d glyphs, cell %dx%d, %d B data" % (out, len(glyphs), adv, cell_h, len(data)))


if __name__ == "__main__":
    main()
