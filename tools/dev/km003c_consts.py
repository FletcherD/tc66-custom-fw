"""Generate rust/src/km003c_consts.rs: the precomputed KM003C MemoryRead
exchange for the HardwareID block (0x40010450, 12 B), so the firmware answers
it without any AES code (docs/HARDWARE.md "AdcQueue streaming").

The request's 32-B payload is AES-128-ECB(key0) of [addr, size, 0xFFFFFFFF,
CRC32 of those 12 B, 16 x 0xFF] — fixed for a given (addr, size), so the
firmware matches its first block. The reply is a plaintext confirmation body
(addr, size, magic, CRC32) followed by the HardwareID + 4 B 0xFF padding,
encrypted with key0. Protocol reference: github.com/okhsunrog/km003c-protocol-research
(docs/features/authentication.md)."""
import argparse
import binascii
import os
import struct

from Crypto.Cipher import AES

KEY0 = b"Lh2yfB7n6X7d9a5Z"  # MemoryRead key
HWID_ADDR = 0x40010450
HWID_SIZE = 12
# 6-B identifier, 0x0D 0xFF separator, LE u16 device id, 0xFFFF padding —
# the real device's layout; content is ours (hosts only echo it back in
# StreamingAuth, which this firmware grants regardless).
HWID = b"TC66FW" + b"\x0d\xff" + struct.pack("<H", 0x0066) + b"\xff\xff"


def rust_bytes(name, data, doc):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"/// {doc}\npub const {name}: [u8; {len(data)}] = [{body}];\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    ap.add_argument("--out", default=os.path.join(here, "../../rust/src/km003c_consts.rs"),
                    help="generated Rust file")
    args = ap.parse_args()

    aes = AES.new(KEY0, AES.MODE_ECB)
    head = struct.pack("<III", HWID_ADDR, HWID_SIZE, 0xFFFFFFFF)
    crc = binascii.crc32(head) & 0xFFFFFFFF
    req_block0 = aes.encrypt(head + struct.pack("<I", crc))
    confirm = head + struct.pack("<I", crc)
    data = aes.encrypt(HWID + b"\xff" * 4)

    out = ["// Generated by tools/dev/km003c_consts.py — do not edit.\n\n"]
    out.append(rust_bytes("HWID_REQ_BLOCK0", req_block0,
                          "First AES block of a MemoryRead(0x40010450, 12) request payload."))
    out.append(rust_bytes("HWID_CONFIRM", confirm,
                          "MemoryRead confirmation body: addr, size, magic, CRC32."))
    out.append(rust_bytes("HWID_DATA", data,
                          "The HardwareID block (+4 B 0xFF), AES-128-ECB(key0)."))
    with open(args.out, "w") as f:
        f.write("".join(out))
    print(f"wrote {args.out} (HardwareID {HWID.hex()})")


if __name__ == "__main__":
    main()
