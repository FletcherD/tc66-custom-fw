fn crc16_modbus(data: &[u8]) -> u16 {
    let mut crc: u16 = 0xFFFF;
    for &b in data {
        crc ^= b as u16;
        for _ in 0..8 {
            crc = if crc & 1 != 0 { (crc >> 1) ^ 0xA001 } else { crc >> 1 };
        }
    }
    crc
}

fn put_u32(buf: &mut [u8; 192], off: usize, v: u32) {
    buf[off..off + 4].copy_from_slice(&v.to_le_bytes());
}

/// Fill the template with live values, checksum, encrypt. Units are the wire
/// units: v = 1e-4 V, i = 1e-5 A, p = 1e-4 W, r = 1e-1 ohm.
#[inline(never)]
pub fn build(out: &mut [u8; 192], v: u32, i: u32, p: u32, r: u32) {
    *out = TEMPLATE;
    put_u32(out, 48, v);
    put_u32(out, 52, i);
    put_u32(out, 56, p);
    put_u32(out, 68, r);
    for b in 0..3 {
        let crc = crc16_modbus(&out[b * 64..b * 64 + 60]) as u32;
        let bytes = crc.to_le_bytes();
        out[b * 64 + 60..b * 64 + 64].copy_from_slice(&bytes);
    }
    let cipher = Aes256::new(GenericArray::from_slice(&KEY));
    for blk in out.chunks_exact_mut(16) {
        cipher.encrypt_block(GenericArray::from_mut_slice(blk));
    }
}
